def build_report(hosts: list) -> str:
    everything = [i for h in hosts for i in h["instances"] if not i.get("error")]
    flowfuse = [i for i in everything if i.get("is_flowfuse")]
    # FlowFuse instances are a migration source, not a deploy target — they are
    # kept out of the plain-instance analysis so they cannot skew it.
    instances = [i for i in everything if not i.get("is_flowfuse")]
    L = []
    add = L.append

    add("# Inventory report\n")
    add(f"{len(everything)} Node-RED runtimes across "
        f"{len([h for h in hosts if not h['error']])} reachable hosts — "
        f"{len(instances)} plain, {len(flowfuse)} under FlowFuse.\n")

    failed = [h for h in hosts if h["error"]]
    if failed:
        add("## Unreachable hosts\n")
        for h in failed:
            add(f"- **{h['host']}** — {h['error']}")
        add("")

    empty = [h for h in hosts if not h["error"] and not h["instances"]]
    if empty:
        add("## Hosts with no Node-RED container\n")
        add("Everything these hosts do run, so a differently-named instance is visible:\n")
        for h in empty:
            add(f"**{h['host']}**\n")
            add("```")
            L.extend(h.get("all_containers") or ["(no containers at all)"])
            add("```\n")

    # --- FlowFuse ----------------------------------------------------------
    if flowfuse:
        add("## FlowFuse instances — migration source\n")
        add(f"{len(flowfuse)} runtimes run under FlowFuse and are to become plain "
            "Node-RED containers as part of this project. They are excluded from the "
            "analysis below, because they answer different questions.\n")
        add("The decisive one: **where does the authoritative flow live?** If FlowFuse "
            "keeps it in its platform rather than in `/data/flows.json`, the file on disk "
            "is a cache or absent, and the migration is an export from FlowFuse — not a "
            "file copy.\n")
        for i in flowfuse:
            ff = i.get("flowfuse") or {}
            add(f"### {i['host']}/{i['name']}\n")
            add(f"- image: `{i['image']}`")
            add(f"- Node-RED version: `{ff.get('node_red_version') or 'unknown'}`")
            add(f"- storage module: `{'; '.join(ff.get('storage_module') or []) or 'not found in settings.js'}`")
            add(f"- flow files on disk: {', '.join(f'`{p}`' for p in ff.get('flow_files') or []) or '**none found**'}")
            forge = {k: v for k, v in (i.get("env") or {}).items() if k.startswith("FORGE_")}
            if forge:
                add("- FlowFuse env (secret values masked):")
                for k, v in sorted(forge.items()):
                    add(f"  - `{k}` = `{v}`")
            if i.get("palette"):
                add(f"- palette: {', '.join(sorted(i['palette']))}")
            for d, lines in (ff.get("listing") or {}).items():
                add(f"\n<details><summary><code>{d}</code></summary>\n")
                add("```")
                L.extend(lines)
                add("```\n</details>")
            add("")

    # --- Q1: settings.js ---------------------------------------------------
    add("## Q1 — Are the settings.js files the same file?\n")
    add("Plain Node-RED instances only; FlowFuse-managed settings.js files are "
        "generated by the launcher and are not part of this comparison.\n")
    add("Grouped on what the file *configures*: comments, indentation and blank lines "
        "removed, secret values and per-instance fields masked. Node-RED ships every "
        "option commented out and rewrites those comment blocks between versions, so "
        "grouping on the raw text separates files that configure exactly the same thing.\n")

    groups: dict[str, list] = {}
    literal: dict[str, list] = {}
    for i in instances:
        if i.get("settings"):
            groups.setdefault(i["settings"].get("hash_semantic") or "?", []).append(i)
            literal.setdefault(i["settings"]["hash_ignoring_per_instance"], []).append(i)
    if len(groups) == 1:
        add("**One group.** Every settings.js configures the same thing.\n")
        add("→ One template in the repo plus env overrides.\n")
    else:
        add(f"**{len(groups)} groups** by configuration "
            f"({len(literal)} by literal text — the difference is comment and whitespace churn "
            "between Node-RED versions, which needs no reconciling).\n")
        add("→ Reconcile the configuration differences; see the diffs below.\n")
    for idx, (h, members) in enumerate(sorted(groups.items(), key=lambda kv: -len(kv[1])), 1):
        add(f"- group {idx} (`{h}`, {len(members)}): " +
            ", ".join(f"{m['host']}/{m['name']}" for m in members))
    add("")

    if len(groups) > 1:
        add("### Diffs between group representatives\n")
        reps = [members[0] for _, members in sorted(groups.items(), key=lambda kv: -len(kv[1]))]
        base = reps[0]
        base_txt = (INV / "settings" / f"{base['host']}__{base['name']}.settings.js").read_text(encoding="utf-8")
        for other in reps[1:]:
            other_txt = (INV / "settings" / f"{other['host']}__{other['name']}.settings.js").read_text(encoding="utf-8")
            diff = list(difflib.unified_diff(
                strip_comments(mask_per_instance(base_txt)).splitlines(),
                strip_comments(mask_per_instance(other_txt)).splitlines(),
                fromfile=f"{base['host']}/{base['name']}",
                tofile=f"{other['host']}/{other['name']}",
                lineterm="", n=2,
            ))
            add(f"<details><summary>{base['host']}/{base['name']} vs "
                f"{other['host']}/{other['name']} — {len(diff)} diff lines</summary>\n")
            add("```diff")
            L.extend(diff[:200])
            if len(diff) > 200:
                add(f"... {len(diff) - 200} more lines")
            add("```\n</details>\n")

    add("### Per-instance fields\n")
    add("`admin_root` is the probed value — what the running instance actually answers on, "
        "not what settings.js appears to say.\n")
    add("| instance | Node-RED | admin_root (probed) | settings.js says | dns_search | credentialSecret | adminAuth |")
    add("|---|---|---|---|---|---|---|")
    for i in sorted(instances, key=lambda x: (x["host"], x["name"])):
        s = i.get("settings") or {}
        a = i.get("admin_api") or {}
        probed = a.get("admin_root")
        probed_txt = "**unresolved**" if not a.get("resolved") else f"`{probed or '/'}`"
        claimed = s.get("httpAdminRoot")
        flag = "" if a.get("agrees_with_settings") or not a.get("resolved") else " ⚠"
        add(f"| {i['host']}/{i['name']} | {i.get('node_red_version') or '?'} | {probed_txt}{flag} | "
            f"`{claimed or 'unset'}` | {', '.join(i['dns_search']) or '—'} | "
            f"{'set' if s.get('credentialSecret_set') else 'GENERATED'} | "
            f"{'on' if s.get('adminAuth_set') else '**off**'} |")
    add("")
    noauth = [i for i in instances if not (i.get("settings") or {}).get("adminAuth_set")]
    if noauth:
        add(f"**adminAuth is off on {len(noauth)}:** " +
            ", ".join(f"{i['host']}/{i['name']}" for i in noauth) +
            ". Its editor and Admin API are open to anyone who can reach the container.\n")

    # --- Q4/Q5: flows -------------------------------------------------------
    add("## Q4/Q5 — Flow sizes, and which instances share logic\n")
    add("| instance | nodes | bytes | node types | palette | own npm modules |")
    add("|---|---|---|---|---|---|")
    for i in sorted(instances, key=lambda x: (x["host"], x["name"])):
        f = i.get("flows") or {}
        pal = ", ".join(sorted(i.get("palette", {}))) or "—"
        ext = ", ".join(f.get("external_modules", [])) or "—"
        add(f"| {i['host']}/{i['name']} | {f.get('nodes', '?')} | {f.get('bytes', '?')} | "
            f"{f.get('node_types', '?')} | {pal} | {ext} |")
    add("")

    sigs: dict[str, list] = {}
    for i in instances:
        if (i.get("flows") or {}).get("signature"):
            sigs.setdefault(i["flows"]["signature"], []).append(i)
    shared = {s: m for s, m in sigs.items() if len(m) > 1}
    if shared:
        add("Instances running the same logic (matching node type/name multiset, ids and layout ignored):\n")
        for s, members in shared.items():
            add(f"- `{s}`: " + ", ".join(f"{m['host']}/{m['name']}" for m in members))
        add("\n→ Each group becomes one `apps/<name>/` directory.\n")
    else:
        add("No two instances share a flow signature — every instance is a one-off, "
            "so every instance gets its own `apps/` directory or `app: null`.\n")

    ext_users = [i for i in instances if (i.get("flows") or {}).get("external_modules")]
    add(f"Function nodes declaring their own npm module: "
        f"{'NONE — the baked image is a real guarantee' if not ext_users else 'FOUND, see table above'}\n")

    # --- transport ----------------------------------------------------------
    add("## Admin API probe\n")
    add("Each candidate root tried as `<root>/flows`. 401 = reachable, adminAuth active. "
        "200 = reachable, auth off. 404 = the runtime answers but not on that path. "
        "000 = nothing listening.\n")
    add("| instance | probes | resolved root |")
    add("|---|---|---|")
    for i in sorted(instances, key=lambda x: (x["host"], x["name"])):
        a = i.get("admin_api") or {}
        probes = " ".join(f"`{r}`={c}" for r, c in (a.get("probes") or {}).items())
        res = f"`{a.get('admin_root') or '/'}`" if a.get("resolved") else "**none answered**"
        add(f"| {i['host']}/{i['name']} | {probes or '—'} | {res} |")
    add("")
    unresolved = [i for i in instances if not (i.get("admin_api") or {}).get("resolved")]
    if unresolved:
        add(f"**{len(unresolved)} unresolved.** No candidate root answered — the admin root is "
            "something else, or the runtime is not on 1880. These cannot get a `registry.yml` "
            "entry until the root is known.\n")

    missing = [i for i in instances if i.get("flows_lookup")]
    if missing:
        add("## Instances whose flow file was not found\n")
        for i in missing:
            fl = i["flows_lookup"]
            add(f"### {i['host']}/{i['name']}\n")
            add(f"- tried: {', '.join(f'`{t}`' for t in fl['tried'])}")
            add(f"- data mount: `{fl['data_mount'] or 'none — named volume'}`")
            add(f"- json files under /data: {', '.join(f'`{p}`' for p in fl['found']) or 'none'}")
            if fl.get("listing"):
                add("\n```")
                L.extend(fl["listing"])
                add("```")
            add("")

    # --- images and compose --------------------------------------------------
    add("## Image tags and compose blast radius\n")
    add("| instance | image | pinned | restart | published ports | compose service | compose file |")
    add("|---|---|---|---|---|---|---|")
    for i in sorted(instances, key=lambda x: (x["host"], x["name"])):
        add(f"| {i['host']}/{i['name']} | `{i['image']}` | "
            f"{'yes' if i['image_pinned'] else '**NO**'} | {i['restart_policy']} | "
            f"{i['published_ports'] or 'none'} | {i['compose_service']} | `{i['compose_file']}` |")
    add("")
    for h in hosts:
        for f, services in (h.get("compose_neighbours") or {}).items():
            others = [s for s in services if s and not re.search(r"node.?red", s, re.I)]
            if others:
                add(f"- `{h['host']}:{f}` also holds: {', '.join(others)} "
                    f"— a bare `docker compose up -d` recreates these")
    add("")

    add("## Not answerable from the hosts\n")
    add("- **Harbor project for Node-RED images.** Whether a `dap-nodered` project exists "
        "and which GitLab CI variable holds its push credential is a Harbor/GitLab question.\n")
    return "\n".join(L)


def build_registry_draft(hosts: list) -> str:
    L = ["# Generated by scripts/collect-inventory.py — review before use.",
         "# Credential ids and image tags are placeholders.",
         "",
         "global_variables: {}",
         "",
         "instances:"]
    for h in hosts:
        for i in h["instances"]:
            if i.get("error"):
                continue
            a = i.get("admin_api") or {}
            if i.get("is_flowfuse"):
                L.append(f"  # {i['name']} on {h['host']} runs under FlowFuse — migrate it to a")
                L.append(f"  # plain container first, then add it here.")
            L += [
                f"  - name: {i['name']}",
                f"    host: {h['host']}",
                f"    app: null",
                f"    admin_root: {a.get('admin_root') or '/'}"
                + ("" if a.get("resolved") else "  # UNRESOLVED — no candidate root answered"),
                f"    auth_credential_id: CHANGEME-{h['host']}-{i['name']}-auth",
                f"    credential_secret_id: CHANGEME-{h['host']}-{i['name']}-credsecret",
                f"    dns_search: [{', '.join(i['dns_search'])}]",
                f"    image_tag: CHANGEME  # currently running {i['image']}",
                f"    variables: {{}}",
            ]
    return "\n".join(L) + "\n"


