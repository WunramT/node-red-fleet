SETTINGS_FIELDS = {
    "httpAdminRoot": r"""httpAdminRoot\s*:\s*["']([^"']*)["']""",
    "flowFile": r"""flowFile\s*:\s*["']([^"']*)["']""",
    "functionExternalModules": r"""functionExternalModules\s*:\s*(true|false)""",
    "flowFilePretty": r"""flowFilePretty\s*:\s*(true|false)""",
}

SETTINGS_PRESENT = ("credentialSecret", "adminAuth", "contextStorage")

# Anything that is a Node-RED runtime, however it is packaged.
RUNTIME_HINT = re.compile(r"node.?red|flowfuse|flowforge", re.I)
FLOWFUSE_HINT = re.compile(r"flowfuse|flowforge", re.I)

# Env var names whose values stay on the host.
SECRET_ENV = re.compile(r"pass|secret|token|key|credential|auth", re.I)


def collect_host(cfg) -> dict:
    host = {"host": cfg["name"], "instances": [], "error": None}
    remote = None
    try:
        remote = Remote(cfg)
        host["fqdn"] = remote.run("hostname -f")

        # Match on the image as well as the container name — a site that named
        # its container something else still runs a node-red image. FlowFuse
        # instances are Node-RED too, under a name that says nothing about it.
        host["all_containers"] = remote.run(
            "docker ps -a --format '{{.Names}}\t{{.Image}}'"
        ).splitlines()
        names = [
            line.split("\t")[0]
            for line in host["all_containers"]
            if RUNTIME_HINT.search(line)
        ]

        # Every service sharing a compose file with Node-RED — the blast
        # radius of a bare `docker compose up -d`.
        host["compose_neighbours"] = {}

        for name in names:
            raw = remote.run(f"docker inspect {name}")
            try:
                info = json.loads(raw)[0]
            except Exception:
                host["instances"].append({"name": name, "error": "docker inspect failed"})
                continue

            cfg_ = info.get("Config", {})
            hostcfg = info.get("HostConfig", {})
            labels = cfg_.get("Labels") or {}
            nets = info.get("NetworkSettings", {}).get("Networks", {}) or {}

            mount = next(
                (m.get("Source") for m in info.get("Mounts", [])
                 if m.get("Destination") == "/data"),
                "",
            )
            compose_file = labels.get("com.docker.compose.project.config_files", "")

            inst = {
                "name": name,
                "host": cfg["name"],
                "image": cfg_.get("Image"),
                "image_pinned": bool(cfg_.get("Image")) and ":" in str(cfg_.get("Image"))
                                and not str(cfg_.get("Image")).endswith((":latest", ":main", ":master")),
                "state": info.get("State", {}).get("Status"),
                "restart_policy": hostcfg.get("RestartPolicy", {}).get("Name"),
                "published_ports": hostcfg.get("PortBindings") or {},
                "dns_search": hostcfg.get("DnsSearch") or [],
                "networks": sorted(nets),
                "ip": next((v.get("IPAddress") for v in nets.values() if v.get("IPAddress")), ""),
                "compose_project": labels.get("com.docker.compose.project"),
                "compose_service": labels.get("com.docker.compose.service"),
                "compose_file": compose_file,
                "data_mount": mount,
            }

            # Filter on the project, not the config_files label — that label can
            # hold a comma-separated list, which an exact-match filter misses,
            # and a silent empty result reads as "nothing else shares the file".
            project = labels.get("com.docker.compose.project")
            if compose_file and project and compose_file not in host["compose_neighbours"]:
                host["compose_neighbours"][compose_file] = sorted(set(
                    remote.run(
                        f"docker ps -a --filter 'label=com.docker.compose.project={project}' "
                        "--format '{{index .Labels \"com.docker.compose.service\"}}'"
                    ).split()
                ))

            # --- FlowFuse ------------------------------------------------------
            # FlowFuse runs Node-RED under its own launcher and can keep the
            # authoritative flow in its platform rather than in /data/flows.json.
            # Nothing here assumes a layout — it reports what is actually there,
            # so the migration off it is designed against facts.
            env_pairs = [e.split("=", 1) for e in (cfg_.get("Env") or []) if "=" in e]
            inst["env"] = {
                k: ("<masked>" if SECRET_ENV.search(k) else v) for k, v in env_pairs
            }
            inst["is_flowfuse"] = bool(
                FLOWFUSE_HINT.search(str(cfg_.get("Image")))
                or FLOWFUSE_HINT.search(json.dumps(labels))
                or any(FLOWFUSE_HINT.search(k) or k.startswith("FORGE_") for k, _ in env_pairs)
            )

            if inst["is_flowfuse"]:
                ff = {"listing": {}}
                for d in ("/data", "/data/.node-red", "/opt/flowforge", "/usr/src/flowforge-nr-launcher"):
                    out = remote.run(f"docker exec {name} sh -lc 'ls -la {d} 2>/dev/null | head -40'")
                    if out:
                        ff["listing"][d] = out.splitlines()
                ff["flow_files"] = remote.run(
                    f"docker exec {name} sh -lc "
                    "'find / -maxdepth 6 -name \"flows*.json\" -not -path \"*/node_modules/*\" "
                    "2>/dev/null | head -20'"
                ).splitlines()
                ff["storage_module"] = remote.run(
                    f"docker exec {name} sh -lc "
                    "'grep -rhoE \"storageModule.{0,60}\" /data/settings.js /usr/src/*/settings.js "
                    "2>/dev/null | head -5'"
                ).splitlines()
                ff["launcher_version"] = remote.run(
                    f"docker exec {name} sh -lc "
                    "'cat /usr/src/*/package.json 2>/dev/null | head -20'"
                ).splitlines()
                ff["node_red_version"] = remote.run(
                    f"docker exec {name} sh -lc "
                    "'node -e \"console.log(require(\\\"node-red/package.json\\\").version)\" 2>/dev/null'"
                )
                inst["flowfuse"] = ff

            # --- settings.js -------------------------------------------------
            # Every field is read from the comment-stripped text. Node-RED ships
            # settings.js with each option present but commented out, so matching
            # the raw file reports a template default as if it were configured.
            settings = remote.read(name, mount, "settings.js")
            if settings:
                masked = mask_secrets(settings)
                live = strip_comments(settings)
                inst["settings"] = {
                    "hash_exact": sha(masked),
                    "hash_ignoring_per_instance": sha(mask_per_instance(masked)),
                    "hash_semantic": sha(semantic(mask_per_instance(masked))),
                    "bytes": len(settings),
                }
                for field, pattern in SETTINGS_FIELDS.items():
                    m = re.search(pattern, live)
                    inst["settings"][field] = m.group(1) if m else None
                for field in SETTINGS_PRESENT:
                    inst["settings"][f"{field}_set"] = bool(
                        re.search(rf"^\s*{field}\s*:", live, re.M)
                    )
                (INV / "settings").mkdir(parents=True, exist_ok=True)
                (INV / "settings" / f"{cfg['name']}__{name}.settings.js").write_text(masked, encoding="utf-8")
            else:
                inst["settings"] = None

            # --- flows.json --------------------------------------------------
            flow_file = (inst.get("settings") or {}).get("flowFile") or "flows.json"
            flows_raw = remote.read(name, mount, flow_file)
            if not flows_raw and flow_file != "flows.json":
                flows_raw = remote.read(name, mount, "flows.json")
            if not flows_raw:
                # Report what is actually in the data directory rather than a bare '?'.
                inst["flows_lookup"] = {
                    "tried": [flow_file, "flows.json"],
                    "data_mount": mount,
                    "listing": remote.run(
                        f"docker exec {name} sh -lc 'ls -la /data 2>/dev/null | head -30'"
                    ).splitlines(),
                    "found": remote.run(
                        f"docker exec {name} sh -lc "
                        "'find /data -maxdepth 2 -name \"*.json\" -not -path \"*/node_modules/*\" "
                        "2>/dev/null | head -20'"
                    ).splitlines(),
                }
            if flows_raw:
                try:
                    nodes = json.loads(flows_raw)
                    norm = normalize_flow(nodes)
                    inst["flows"] = {
                        "bytes": len(flows_raw),
                        "nodes": len(nodes),
                        "normalized_hash": sha(json.dumps(norm, sort_keys=True)),
                        "signature": flow_signature(nodes),
                        "external_modules": sorted({
                            n["module"] for n in nodes
                            if isinstance(n, dict) and n.get("module")
                        }),
                        "node_types": len({
                            n.get("type") for n in nodes if isinstance(n, dict)
                        }),
                    }
                    SAMPLES.mkdir(parents=True, exist_ok=True)
                    (SAMPLES / f"{cfg['name']}__{name}.flows.json").write_text(flows_raw, encoding="utf-8")
                except json.JSONDecodeError as exc:
                    inst["flows"] = {"error": f"unparseable: {exc}"}
            else:
                inst["flows"] = None

            # --- package.json ------------------------------------------------
            pkg = remote.read(name, mount, "package.json")
            if pkg:
                try:
                    inst["palette"] = json.loads(pkg).get("dependencies", {})
                except json.JSONDecodeError:
                    inst["palette"] = {"error": "unparseable"}
            else:
                inst["palette"] = {}

            # --- credential files: existence only ------------------------------
            for f in ("flows_cred.json", ".config.runtime.json"):
                probe = f"test -f '{mount}/{f}'" if mount else f"docker exec {name} test -f /data/{f}"
                inst[f.strip('.').replace('.', '_')] = remote.run(f"{probe} && echo yes || echo no") == "yes"

            # --- Admin API: probe, do not trust settings.js --------------------
            # The admin root is the one field deploy.py cannot get wrong, so it
            # is established empirically: 401 or 200 on <root>/flows is the
            # answer, whatever settings.js appears to say.
            if inst["ip"]:
                parsed = ((inst.get("settings") or {}).get("httpAdminRoot") or "").rstrip("/")
                candidates, seen = [], set()
                for root in (parsed, "", f"/{name}", "/admin", "/node-red", "/nodered"):
                    if root not in seen:
                        seen.add(root)
                        candidates.append(root)
                probes = {}
                for root in candidates:
                    probes[root or "/"] = remote.run(
                        f"curl -s -o /dev/null -m 5 -w '%{{http_code}}' "
                        f"'http://{inst['ip']}:1880{root}/flows' || echo 000"
                    )
                live = [r for r, c in probes.items() if c in ("401", "200")]
                inst["admin_api"] = {
                    "probes": probes,
                    "admin_root": ("" if live and live[0] == "/" else (live[0] if live else None)),
                    "resolved": bool(live),
                    "agrees_with_settings": bool(live) and (live[0].rstrip("/") or "") == parsed,
                }

            # --- Node-RED version ---------------------------------------------
            # Explains why two settings.js differ without either being edited.
            inst["node_red_version"] = remote.run(
                f"docker exec {name} sh -lc "
                "'node -p \"require(\\\"/usr/src/node-red/node_modules/node-red/package.json\\\").version\" "
                "2>/dev/null || node -p \"require(\\\"node-red/package.json\\\").version\" 2>/dev/null'"
            ).strip()

            host["instances"].append(inst)

    except Exception as exc:
        host["error"] = f"{type(exc).__name__}: {exc}"
        traceback.print_exc()
    finally:
        if remote:
            remote.close()
    return host


