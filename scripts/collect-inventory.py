def main():
    # Windows consoles default to cp1252; flow node names contain arrows and emoji.
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass

    try:
        import paramiko  # noqa: F401
    except ImportError:
        sys.exit("paramiko is missing — run: pip install paramiko")

    local = ROOT / "hosts.local.json"
    targets = json.loads(local.read_text(encoding="utf-8")) if local.exists() else HOSTS
    targets = [t for t in targets if t.get("user") and (t.get("password") or t.get("key_file"))]
    if not targets:
        sys.exit("No credentials configured — fill in HOSTS or create hosts.local.json.")

    INV.mkdir(parents=True, exist_ok=True)
    results = []
    for cfg in targets:
        print(f"[{cfg['name']}] connecting ...", flush=True)
        host = collect_host(cfg)
        n = len([i for i in host["instances"] if not i.get("error")])
        print(f"[{cfg['name']}] {'ERROR: ' + host['error'] if host['error'] else f'{n} instances'}", flush=True)
        (INV / f"{cfg['name']}.json").write_text(json.dumps(host, indent=2, sort_keys=True), encoding="utf-8")
        results.append(host)

    (INV / "REPORT.md").write_text(build_report(results), encoding="utf-8")
    (ROOT / "registry.draft.yml").write_text(build_registry_draft(results), encoding="utf-8")

    flows = sorted(SAMPLES.glob("*.flows.json")) if SAMPLES.exists() else []
    expected = [i for h in results for i in h["instances"]
                if not i.get("error") and (i.get("flows") or {}).get("nodes") is not None]

    print("\n" + "=" * 70)
    print("Wrote:")
    print(f"  {INV / 'REPORT.md'}")
    print(f"  {ROOT / 'registry.draft.yml'}")
    print(f"  {SAMPLES}{'/' if flows else ''}")
    for f in flows:
        print(f"      {f.name}")
    print("=" * 70)

    if len(flows) != len(expected):
        print(f"\nWARNING: {len(expected)} instances returned a flow but {len(flows)} files "
              f"are in {SAMPLES} — something failed to write there.")
    elif flows:
        print(f"\n{len(flows)} flow files. They are in {SAMPLES}, NOT in {INV}.")

    print("\nSend inventory/REPORT.md, and commit samples/ so normalize.py can run against it.")


if __name__ == "__main__":
    main()
